-- Tiny "orders" schema that the worked example tests.
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_customer') THEN CREATE ROLE app_customer NOLOGIN; END IF;
END $$;

CREATE SCHEMA orders;

CREATE TABLE orders.customer_order (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id int  NOT NULL,
  status      text NOT NULL DEFAULT 'new'
              CONSTRAINT customer_order_status_chk CHECK (status IN ('new', 'paid', 'shipped', 'cancelled')),
  note        text,
  total_cents int  NOT NULL CHECK (total_cents >= 0)
);

CREATE TABLE orders.order_line (
  id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id bigint NOT NULL REFERENCES orders.customer_order (id),
  sku      text   NOT NULL,
  qty      int    NOT NULL CHECK (qty > 0)
);

-- D002: a shipped order, and everything under it, is frozen.
CREATE FUNCTION orders.guard_shipped_order() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.status = 'shipped' THEN RAISE EXCEPTION 'shipped order is frozen'; END IF;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END $$;

CREATE FUNCTION orders.guard_shipped_line() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE o bigint;
BEGIN
  FOR o IN SELECT DISTINCT x FROM unnest(ARRAY[
      CASE WHEN TG_OP IN ('UPDATE', 'DELETE') THEN OLD.order_id END,
      CASE WHEN TG_OP IN ('UPDATE', 'INSERT') THEN NEW.order_id END]) AS x WHERE x IS NOT NULL LOOP
    IF EXISTS (SELECT 1 FROM orders.customer_order WHERE id = o AND status = 'shipped') THEN
      RAISE EXCEPTION 'shipped order is frozen';
    END IF;
  END LOOP;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER customer_order_frozen BEFORE UPDATE OR DELETE ON orders.customer_order
  FOR EACH ROW EXECUTE FUNCTION orders.guard_shipped_order();
CREATE TRIGGER order_line_frozen BEFORE INSERT OR UPDATE OR DELETE ON orders.order_line
  FOR EACH ROW EXECUTE FUNCTION orders.guard_shipped_line();

-- D003: customer read paths take the customer id; no direct table access.
CREATE FUNCTION orders.get_order(p_customer_id int, p_order_id bigint)
RETURNS SETOF orders.customer_order LANGUAGE sql STABLE AS $$
  SELECT * FROM orders.customer_order WHERE id = p_order_id AND customer_id = p_customer_id
$$;
CREATE FUNCTION orders.list_orders(p_customer_id int, p_status text DEFAULT NULL)
RETURNS SETOF orders.customer_order LANGUAGE sql STABLE AS $$
  SELECT * FROM orders.customer_order WHERE customer_id = p_customer_id AND (p_status IS NULL OR status = p_status)
$$;

REVOKE ALL ON ALL FUNCTIONS IN SCHEMA orders FROM PUBLIC;
GRANT USAGE ON SCHEMA orders TO app_customer;
GRANT EXECUTE ON FUNCTION orders.get_order(int, bigint), orders.list_orders(int, text) TO app_customer;
